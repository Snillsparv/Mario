// Convert row strings into { w, h, bits: Uint8Array } (row-major, 1 = filled).
function compile(table, height) {
  const glyphs = {};
  for (const [ch, rows] of Object.entries(table)) {
    const w = rows[0].length;
    const bits = new Uint8Array(w * height);
    rows.forEach((row, y) => {
      for (let x = 0; x < w; x++) bits[y * w + x] = row[x] === '#' ? 1 : 0;
    });
    glyphs[ch] = { w, h: height, bits, rows };
  }
  return glyphs;
}

// height: rows per glyph; spacing: empty pixels between glyphs; digitWidth: fixed
// advance used for counters so numbers do not jitter as they change.
export const BIG_FONT = { name: 'big', height: 10, spacing: 1, digitWidth: 8, glyphs: compile(big, 10) };
export const SMALL_FONT = { name: 'small', height: 9, spacing: 1, digitWidth: 5, glyphs: compile(small, 9) };

// Glyph for a character; the big font has no lowercase, so letters are upper-cased there.
export function glyphOf(font, ch) {
  return font.glyphs[ch] || font.glyphs[ch.toUpperCase()] || null;
}

// Characters of `text` the font cannot draw (used by tests and as a dev-time guard).
export function missingGlyphs(font, text) {
  const out = new Set();
  for (const ch of text) if (!glyphOf(font, ch)) out.add(ch);
  return [...out];
}

const isDigit = (ch) => ch >= '0' && ch <= '9';

// Horizontal advance of one glyph in font pixels (fixed-width digits for counters).
export function advanceOf(font, ch, g, fixedDigits = false) {
  return (fixedDigits && isDigit(ch) ? font.digitWidth : g.w) + font.spacing;
}

// Left inset that centres a digit in its fixed-width cell.
export function digitInset(font, ch, g, fixedDigits = false) {
  return fixedDigits && isDigit(ch) ? (font.digitWidth - g.w) / 2 : 0;
}

// Width in font pixels of `text` (glyph widths + spacing between glyphs).
export function measureText(font, text, fixedDigits = false) {
  let w = 0;
  for (const ch of text) {
    const g = glyphOf(font, ch);
    if (g) w += advanceOf(font, ch, g, fixedDigits);
  }
  return w ? w - font.spacing : 0;
}
